# DTC FORTH IS MORE ELEGANT THAN ITC/STC ON SH4A
# R8:  W
# R9:  UP
# R10: TOS
# R11: IP
# R12: PSP
# R13: RSP
# R14: CALL/TAIL TEMP REGISER

	.INCLUDE "DEFS.S"
	.INCLUDE "MACRO.S"
	.INCLUDE "EARLY.S"

	.PUSHSECTION .pretext
	.P2ALIGN 2, 0
INITIALIZE:
	.GLOBAL INITIALIZE
	MOV.L R14, @-R15
	MOV.L R13, @-R15
	MOV.L R12, @-R15
	MOV.L R11, @-R15
	MOV.L R10, @-R15
	MOV.L R9, @-R15
	MOV.L R8, @-R15
	MOV.L R7, @-R15
	MOV.L R6, @-R15
	MOV.L R5, @-R15
	MOV.L R4, @-R15
	MOV.L R3, @-R15
	MOV.L R2, @-R15
	MOV.L R1, @-R15
	MOV.L R0, @-R15
	STS.L PR, @-R15

COPY_DATA:
	LI32 R0, _datald
	LI32 R1, _sdata
	LI32 R2, _edata
COPY_DATA_LOOP:
	CMP/HS R2, R1
	BT COPY_DATA_DONE
	MOV.L @R0+, R3
	MOV.L R3, @R1
	ADD #4, R1
	BRA COPY_DATA_LOOP
	NOP
COPY_DATA_DONE:

ZERO_BSS:
	LI32 R1, _bbss
	LI32 R2, _ebss
	MOV #0, R3
ZERO_BSS_LOOP:
	CMP/HS R2, R1
	BT ZERO_BSS_DONE
	MOV.L R3, @R1
	ADD #4, R1
	BRA ZERO_BSS_LOOP
	NOP
ZERO_BSS_DONE:

	CALL32 EARLY_INIT

	.PUSHSECTION .rodata.forth_dict
FORTH_DICT_ROM:
	.POPSECTION

	.INCLUDE "CORE.S"
	.INCLUDE "TEST.S"

	.PUSHSECTION .rodata.forth_dict
	.2BYTE 0X0000
FORTH_DICT_ROM_END:
	.POPSECTION

	.PUSHSECTION .rodata
	.P2ALIGN 2, 0
CODE_ROOT:
	FC SELFTEST
	FLIT 'F'
	FC EARLY_EMIT
	FLIT 'T'
	FC EARLY_EMIT
	FLIT 'H'
	FC EARLY_EMIT

	FC BYE
	.POPSECTION

	.PUSHSECTION .text.forth
	.P2ALIGN 2, 0
FORTH_TEXT_START:
	.POPSECTION

	DEFUSER ROOT, ROOT

FORTH_INIT:
	LI32 R13, RSTK_TOP_ROOT
	LI32 R12, PSTK_TOP_ROOT
	LI32 R11, CODE_ROOT
	LI32 R10, TOS_INIT
	LI32 R9, USER_ROOT
	LI32 R0, W_DOCOL
	LDS R0, PR
	NEXT

RETURN_OS:
	CALL32 EARLY_DEINIT
	LDS.L @R15+, PR
	MOV.L @R15+, R0
	MOV.L @R15+, R1
	MOV.L @R15+, R2
	MOV.L @R15+, R3
	MOV.L @R15+, R4
	MOV.L @R15+, R5
	MOV.L @R15+, R6
	MOV.L @R15+, R7
	MOV.L @R15+, R8
	MOV.L @R15+, R9
	MOV.L @R15+, R10
	MOV.L @R15+, R11
	MOV.L @R15+, R12
	MOV.L @R15+, R13
	MOV.L @R15+, R14
	RTS
	NOP
