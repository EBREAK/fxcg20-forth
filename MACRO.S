	.MACRO DEFW LABEL, NAME
		.PUSHSECTION .rodata.forth_dict
		NT_\LABEL:
			.BYTE NLEN_\LABEL
		NAME_\LABEL:
			.ASCII "\NAME"
			.SET NLEN_\LABEL, . - NAME_\LABEL
			.4BYTE W_\LABEL
		.POPSECTION
		.PUSHSECTION .text.forth
			.P2ALIGN 2, 0
		W_\LABEL:
	.ENDM

