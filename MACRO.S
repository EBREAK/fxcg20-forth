		BRA .L_LIU16VE_\@F
		NOP
		.P2ALIGN 1, 0
	.L_LIU16VS_\@F:
		.2BYTE \VAL
	.L_LIU16VE_\@F:
		EXTU.W \REG, \REG
	.ENDM
	

