	.MACRO LI16 REG, VAL
		MOV.W .L_LI16VS_\@F,  \REG
		BRA .L_LI16VE_\@F
		NOP
		.P2ALIGN 1, 0
	.L_LI16VS_\@F:
		.2BYTE \VAL
	.L_LI16VE_\@F:
	.ENDM

	.MACRO LIU16 REG, VAL
