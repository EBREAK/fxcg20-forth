EARLY_INIT:

CPG_INIT:
	LI32 R7, CPG_BASE
	MOV.L @(R32_MSTPCR0, R7), R0
	LI32 R1, ~(CPG_MSTP_SCIF0)
	AND R1, R0
	MOV.L R0, @(R32_MSTPCR0, R7)

SCIF0_INIT:
	LI32 R7, SCIF0_BASE

	MOV.W @(R16_SCSCR, R7), R0
	LIU16 R1, ~(SCIF_REIE | SCIF_RE | SCIF_TE | SCIF_RIE | SCIF_TIE)
	AND R1, R0
	MOV.W R0, @(R16_SCSCR, R7)

	MOV.W @(R16_SCFCR, R7), R0
	MOV #(SCIF_TFRST | SCIF_RFRST), R1
	OR R1, R0
	MOV.W R0, @(R16_SCFCR, R7)

	MOV.W @(R16_SCSCR, R7), R0
	MOV #(SCIF_CKE_ASYNC_INTERNAL), R1
	OR R1, R0
	MOV.W R0, @(R16_SCSCR, R7)

	MOV #(SCIF_CA_ASYNC | SCIF_CHR_8BIT | SCIF_STOP_1BIT | SCIF_CKS_DIV1), R0
	MOV.W R0, @(R16_SCSMR, R7)

	MOV #(3), R0
	MOV.B R0, @(R8_SCBRR, R7)

	LIU16 R1, 8192
WAIT_BAUD_9600_1BIT:
	DT R1
	BF WAIT_BAUD_9600_1BIT
	NOP
	LIU16 R0, (SCIF_RTRG_4 | SCIF_TTRG_4)
	MOV.W R0, @(R16_SCFCR, R7)

	MOV.W @(R16_SCSCR, R7), R0
	MOV #(SCIF_TE | SCIF_RE), R1
	OR R1, R0
	MOV.W R0, @(R16_SCSCR, R7)

	RTS
	NOP

EARLY_DEINIT:
	RTS
	NOP
